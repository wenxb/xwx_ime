/// 短输入(2~3 个字母)本身还能被字面读法解释掉,而单字母简拼弧在那里等价于
/// 「用最不靠谱的读法吃掉整个预算」——与容错门槛⓪同一条理由。目标形态
/// (`zmgai` 5 个字母、`wmjtqbj` 7 个)都在门槛之上。
const MIN_ABBREV_INPUT_LEN: usize = 4;
/// 第三类（首音节合法 + 尾部残缺，`nih` = `ni`+`h`）自己的长度下限。
