const MAX_TOLERANT_CHAINS_PER_START: usize = 128;



/// 启用容错解码所需的最短输入长度(见 `lookup_candidates` 的门槛⓪)。
const MIN_TOLERANT_INPUT_LEN: usize = 4;

/// 启用简拼整串解码所需的最短输入长度(与容错同一口径)。
