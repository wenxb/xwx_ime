/// 字母，与纯缩写类的 ≥2 同一逻辑量级（⑤⑩⑮：通道删除的迁入前置之一）。
const MIN_ABBREV_TAIL_CLASS_LEN: usize = 3;

/// 整串读法一次交几条候选（n-best）。
const ABBREV_CHAIN_NBEST: usize = 4;

/// 整串读法里**每个词**的加性扣分（log10 量纲）。
///
/// 逐词 log 概率相加天生偏爱「多个超高频短词」的长链：实测 `womenjtqbj`
/// 会解成「我满额那就同去吧唧」(`wo man e | na jiu | tong qu | ba ji`)，
/// 因为 那就/同去 这类高频词的 log 概率比 我们今天/去北京 高，而词数多并不
/// 被惩罚。真实句子的先验是「词数越多越不可能」，上游也用 entry credibility
/// 表达同一件事（librime 的 `Grammar::Evaluate` 里 entry_weight 就是这条）。
/// 1.2 ≈ 词数与词频之间的换算尺度，实测能把这批读法压回真实读法之后。
const ABBREV_PER_WORD_PENALTY: f32 = 1.2;

/// 词库源数据的**最低档词频**：`freq == 100` 是「未知/极低频」的约定值——
/// 抽样 233,025 条里 164,371 条（≈70%）落在这一档，其余是 1/2/3/5…；
/// 生成器 `scripts/dict_to_bin.py` 只有 `FREQ_MAX`、没有下限。
///
/// 展示投影用它判断「整串覆盖者是不是都没有真实依据」：全是这一档就等于没有
/// 可靠覆盖（`chu zai na` 全库只有「杵在那 = freq 100」就是这种）。
const FILLER_FREQ_TIER: u64 = 100;

/// —— 简拼纠错（阶段 B，`engine/abbrev_correct.rs`）——
///
/// **触发闸**（三条同时满足才进纠错路径，强读法路径零成本）：
/// ①纯缩写输入（复用 `pure_abbrev_input`）；②长度下限；
/// ③原串整串候选全部没有词条级证据（全 FILLER 档/拼装候选）——
/// 从既有 `ranked` 派生，不加查询。
///
/// 下限取 3：2 字母输入（`nh`）本身歧义面还很小、且纠错变体（删 1 字母
/// 只剩 1 字母）无从谈起证据；实测正例 `dhj`/`sgjj` 都 ≥3。
const MIN_ABBREV_CORRECTION_INPUT_LEN: usize = 3;
/// 1-编辑变体（换位/删字母/邻键替换）的生成上限。
///
/// 7 字母串的完整变体面 = 换位 6 + 删 7 + 替换 ~28 ≈ 41 条；上限 20 时
/// 按代价优先的生成序（换位 → 删 → 同行替换 → 同列替换）恰好保住
/// `wnjtqbj` 的 `n→m`（第 15、16 个）。变体只在触发闸内生成、每条只付
/// 一次 `O(log n)` 二分，20 条的探测成本是微秒级。
const MAX_ABBREV_CORRECTION_VARIANTS: usize = 20;
/// 词条级证据变体的升级上限。升级 = 直接从副索引取条目，**零建格成本**；
/// 上限 2 由用户裁决（2026-10-04）。排序键 = 证据词频降序 → 生成序。
///
/// **已知局限**（实测 `wmjtqbjj` 案例）：删除型链纠正的平局集——原串多打
/// 一个字母、目标读法是多词链时，各删除变体共享同一条首词证据（`wmjt`=
/// 我们今天），词频与覆盖率全同，先验上无法判别谁对；即便把正确变体升级
/// 进解码，跨变体比较时「词数更少的垃圾链」（逐词罚分更轻）仍可能压过
/// 真读法。后果是**漏纠**（呈现的是次优读法），不是误纠（分数闸守门）。
/// 若将来要补：给平局集做预算减半的筛查解码、按分选优后再全量解码最优者
/// ——需要给 `build_abbrev_lattice` 加预算参数，另立一步，不在本阶段。
const MAX_ABBREV_CORRECTION_ENTRY_PROMOTED: usize = 2;
/// 链级证据变体的升级上限：**1**。每条升级要构建一张简拼格（毫秒级），而
/// 链级证据是宽松信号（真实词条的首字母串是变体的前缀 ≠ 整串链读法存在），
/// 多解只是花钱——实测 `wnjtqbj` 的第二条链级变体建格 4.5ms，其读法在
/// 纠正配额（2）的竞争中全部落选，纯属浪费。只解证据词频最高的那条
/// （`wnjtqbj`→`wmjtqbj`=我们今天去北京 靠的就是它）。
const MAX_ABBREV_CORRECTION_CHAIN_PROMOTED: usize = 1;
/// 纠正候选进入候选表的配额（用户裁决③：上限 2 条）。取全部纠正候选里
/// 分数最高的前 2 条；分数闸未过时一条都不进。
const ABBREV_CORRECTION_QUOTA: usize = 2;
/// **分数闸**：纠正串最佳候选要领先原串最佳候选至少这么多（log10 域，
/// 1.0 = 一个数量级）才值得替换原串读法。与全拼门槛②同形，但加了
/// 余量——原串读法已知是弱读法，余量拦住「垃圾纠正打过一个垃圾原串」
/// 的边缘情形（两边都差时不动，宁缺毋滥）。
const ABBREV_CORRECTION_MARGIN: f32 = 1.0;
/// **链级证据**的最短真前缀长度：副索引里存在真实词条的首字母串是变体
/// 的真前缀且 ≥ 该长度，才算「这条变体可能有整串链读法」。
///
/// 取 4：链读法的首词至少 2 个音节，而 ≤3 字母的首字母串在 186 万词条下
/// 几乎处处命中（`wnj`=蜗牛奖、`wmj`=我们家），没有判别力；`wmjt`
 /// （我们今天）这类「双音节词头」才带信息。局限：链首词只有 3 个音节
/// 的读法（`dyjqbg`=打印机+…）拿不到链证据——它们的首词通常本身是
/// 词条级命中，走词条级证据那条路。
const ABBREV_CORRECTION_CHAIN_PREFIX: usize = 4;

/// 「原样上屏剩余串」逃生口候选的分数。
///
/// 语义上它不是词(与回声候选同源),分数必须远低于任何真实候选:实测真实
/// 候选的分数量级在 -5 ~ -70(整句读法是 10 个以上词的 log 概率之和),
/// -1000 足够低且仍是有限值(不引入 -inf/NaN 打印与排序歧义)。
const ESCAPE_HATCH_SCORE: f32 = -1000.0;

/// 容错弧只对**不超过**这么长的窗口开放。
///
/// 短窗口覆盖常见打错(`em`、`hoa`、`haai`、`mem`);上限取 6 是因为
/// **单音节打错一处**里最长的一类是 5~6 字母音节:`xaing`(想,`iang` 内
/// 调换)、`zhuagn`(装,6 字母)——上限 4 时这些窗口整个不开弧,只能靠
/// 把串切成碎音节拼出垃圾候选(实测 `xaing` 首位「喜爱那个」)。
const MAX_TYPO_WINDOW: usize = 6;

/// 声母前缀枚举展开时,每个音节的前缀联想条数上限。
///
/// 「只打了声母/半个音节」的输入(`zh`/`x`/`q`/`zhon`)不是合法音节,
/// 旧的兜底对它做一次整串字节前缀联想:词典按字节序排列,`zh` 的命中
/// 区间以 `zha*` 开头,凑满 `MAX_LOOKUP_RESULTS`(500)即早停——
/// 于是候选被字典序锁死在韵母 `a`,`zhe`/`zhong` 的高频字(这/中)
/// 根本进不了候选(参照实现:libime 的 `PinyinFinal::Invalid` 在 trie 上
/// 枚举全部韵母;librime 的 script_translator 在拼写层就切开了音节)。
///
/// 修法(不改存储层):对「不是合法音节、但是某些音节的前缀」的串,用
/// 编译期静态音节表枚举它的所有音节补全(`zh` → `zha, zhai, zhan, ...`),
/// 每个音节做一次**带配额**的前缀联想,合并后按分排序——每个韵母下的
/// 高频字都有机会进候选,而不是被字节序最小者独占。
///
/// 配额取值理由:
/// - 字节序偏置只在「字典序最前的那几个音节」上,只要每个音节都拿到
///   **非零**条数,偏置即被打破;24 条对单音节字(`zhi` 系 20+ 同音字)
///   的头部够用;
/// - 同音节内的词条按**词频降序**取(mmap 词块本身就是按 freq 降序
///   存的),24 条保证「在/区/钱」这类同音节头部字不会被同音字的
///   数量堆出去(实测配额 16 时 `qu` 系的「区」(该音节第 20 条)
///   进不了前 30,24 可以);
/// - 总查询量的上界:枚举音节数 ≤ 37(`z`:9 个 z 系 + 28 个 zh 系),
///   合并池 ≤ 37 × 24 ≈ 900 条,仍在旧路径单次 500 条的 2 倍以内,
///   排序/打分开销同量级;
/// - 再大(如 64)收益趋零:候选位只有 100 个,字频排序后前 24 条
///   之外的词本就到不了第一页,只是白做多倍打分。
const SYLLABLE_ENUM_QUOTA: usize = 24;

/// 切分格上的一条词边：覆盖 `pinyin[start..end]`，对应该区间查到的一个词。
///
///  是给容错格用的:容错格以精确格为底(克隆),只在错处附近补新边
/// (见 [`ImeEngine::build_tolerant_lattice`])。
#[derive(Debug, Clone)]
struct LatticeEdge {
    /// 边终点（字节位置，`start` 由所在桶隐式给出）。
    end: usize,
    /// 词典词条。
    word: String,
    /// 该词的拼音 key（音节空格分隔，与词典一致），如 `"xi an"`。
    pinyin: String,
    /// 静态词频。
    freq: u64,
    /// 模糊拼音惩罚(对数域加性扣分,非负)。
    ///
    /// 精确匹配的边为 `0.0`;由混淆对展开出的变体边带上
    /// [`expand_fuzzy_scored`] 累计的 `-log10(weight)` 惩罚,
    /// 在 beam / fallback 打分中从路径分里减去。
    fuzzy_penalty: f32,
    /// **容错解码**的编辑惩罚(对数域加性扣分,非负)。
    ///
    /// 走「音节级 ≤1 次编辑」弧的边带上它(见 [`segmenter::TypoSyllables`]
    /// 与 [`Self::build_lattice_with`]),口径是噪声信道的 `-log10 P(编辑操作)`。
    /// 与 `fuzzy_penalty`(模糊音)分开记,是因为两者的**来源不同**:
    /// 模糊音是「用户就是这么念的」,容错是「用户打错了」,代价表不一样。
    typo_penalty: f32,
    /// 本边引入的**容错编辑数**。
    ///
    /// 音节级「≤1 次编辑」弧与「吃掉一段字母」的空词弧各记 1;精确边与
    /// 模糊音边都是 0。口径是「这串里坏了几处」而不是「被删掉几个字母」
    /// ——后者会把一次多打两个字母判成两次编辑,与 [`MAX_TYPO_EDITS`] 的
    /// 语义(最多几处打错)不符。后向 DP 按「剩余预算」递推,整条路径的
    /// 累计编辑数因此真正受限;此前它只卡单次链枚举。
    edit_count: u8,
    /// 空词边:容错解码里「吃掉一段无法解释的字母」的弧。
    ///
    /// 它没有词、没有拼音、没有 LM 转移,只有 `typo_penalty` 一项分数;
    /// 唯一作用是让 beam 能**跨过**多打/打乱的字母继续前进。这种边绝不能
    /// 成为候选(见 [`Self::lattice_candidates`] 的过滤)。
    gap: bool,
    /// **简拼边**:这条边对应的音节链里,至少有一个音节是「只打了首字母、
    /// 其余字母由音节表补全」的读法(`j` → `jin`)。
    ///
    /// 与 `fuzzy_penalty`/`typo_penalty` 分开记,是因为它决定**候选层序**:
    /// 走过简拼边的候选标 [`SpellingKind::Abbrev`](排在精确/模糊之后),
    /// 而简拼的代价仍按对数域扣进 `typo_penalty`(同域相加、量纲一致)。
    /// 逐边记录而不是整格一个开关:同一次简拼解码里,只覆盖前缀的精确词
    /// 不能被连坐标成 Abbrev(那会把它推进「简拼恒 0 桶」,见 `rank.rs`)。
    abbrev: bool,
}

/// beam 里一条部分路径。
///
/// Block A 之后 `lookup_candidates` 只消费「是否为空」(决定走不走
/// 兜底),字段本体仅供 `decode_paths`(测试/调试)读取,故 lib 构建
/// 下标记 `allow(dead_code)`。
#[cfg_attr(not(test), allow(dead_code))]
#[derive(Debug)]
struct BeamPath {
    /// 累计分 = Σ(log10(freq/总词频) + lm_weight × log10 P(word | 路径上文))。
    ///
    /// 两项同量纲（都是对数概率，负值）才可加：词频项对数化后，短语
    /// 不再被百万级原始词频淹没（第 4 步量级失衡修复的核心）。
    score: f32,
    /// 路径已选词的顺序。
    words: Vec<WordSpot>,
}

/// beam 搜索节点：arena 里的一条路径节点，`parent` 指向上一步。
///
/// 用「节点 + 父指针」而不是在每个 BeamPath 里拷贝整条词序列：
/// 扩展只 push 一个节点（O(1) 分配），结束时再沿父链重建词序。
#[derive(Debug)]
struct BeamNode {
    /// 累计分 = Σ(log10(freq/总词频) + lm_weight × log10 P(word | 路径上文))
    ///          - Σ(各边 fuzzy_penalty)(模糊惩罚已揉进分数,非负)。
    score: f32,
    /// 沿路径推进的 LM 状态。
    state: LmState,
    /// 本步选的格边（起点位置, 桶内下标）；根节点为 `None`。
    ///
    /// 边（词/拼音/词频）留在格子里，扩展时只记下标，不复制字符串——
    /// 重建完整路径时才从格取词（每词一次，而不是每扩展一次）。
    edge: Option<(usize, usize)>,
    /// 上一步节点的 arena 下标；根节点为 `None`。
    parent: Option<usize>,
    /// 走到本节点为止**已经用掉**的容错编辑数。
    ///
    /// beam 是路径级搜索,预算必须跟着状态走:同一位置可以有不同的已用
    /// 预算,超预算的节点直接不再扩展。
    used_edits: u8,
}

/// 路径里一个词的位置(字段仅供 `decode_paths` 测试/调试读取)。
#[cfg_attr(not(test), allow(dead_code))]
#[derive(Debug)]
struct WordSpot {
    word: String,
    pinyin: String,
}

