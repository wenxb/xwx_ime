/// 引擎错误：词库/语言模型错误的统一出口。
#[derive(Debug, Error)]
pub enum EngineError {
    /// 词库层错误。
    #[error("词库错误: {0}")]
    Dict(#[from] DictError),
    /// 语言模型层错误。
    #[error("语言模型错误: {0}")]
    Lm(#[from] LmError),
    /// 英文通道错误（词库 I/O 或文件损坏）。
    ///
    /// 它在**查询期**才会浮现（装配期已经校验过一次），向上传播而不是
    /// 吞掉：会话层要能看到它并把英文降级为「本次无英文候选」，中文候选
    /// 与按键行为一律不受影响。
    #[error("英文通道错误: {0}")]
    English(#[from] crate::english::EnglishError),
}

/// 单次查询最多返回的候选数。
///
/// **100 → 512（2026-10-05）**：100 曾是全局硬顶，而简拼/混合读法的候选池
/// 按结构可以远大于它——实测 `data/abbrev.bin` 的 526 个 2 字母键里，
/// 中位数 216 条、p90 570 条，71% 的键超过 100 条。于是「目标词在不在
/// 候选表里」由这个窗口而不是由召回决定：打字模拟评测里二字纯简拼召回
/// 67.1%，未召回样本的 96.8% 恰好停在 ncand=100。
///
/// 窗口不等于显示量：IBus 侧只发**当前页**（9 条，见 `xwx_ibus` 的
/// `refresh_ui`），翻页是会话层在候选表上取模——深表不增加每击键的
/// 序列化成本，只多一次排序（512 条的键预计算 + 排序实测 < 0.1ms）。
/// 上游同量级：librime 对同一批输入迭代出 2700~4400 条候选。
///
/// **为什么不再往上抬（512 → 1024 试过并回退）**：1024 只把二字简拼召回
/// 97.9% → 99.0%（多的那 0.5pp 全是「两字母池里的生僻词」，用户不会翻到
/// 那一页），却把最热的 `zh`/`sh` 从 9.3/9.0ms 推到 **12.1/9.9ms**——正好
/// 顶到 12ms 门槛。`data/abbrev.bin` 的键词条数 p90=570、p99=912，512 已
/// 覆盖绝大多数池子，剩下的是「池子比窗口大」这一档，用窗口去补它不划算。
const MAX_CANDIDATES: usize = 512;
